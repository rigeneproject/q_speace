"""Helper for creating a PR via the GitHub CLI (``gh``).

D4: the AACM loop produces changes in a worktree. The human is
expected to review and merge via PR. This module provides a
thin wrapper around ``gh pr create`` that the CLI can invoke
*opt-in* (``--create-pr-on-success``) after a successful run.

The helper NEVER auto-merges and NEVER force-pushes. It only
opens a PR pointing at the current branch's commits.

If ``gh`` is not installed, the helper skips silently with a
clear message. The loop's main result is unaffected.
"""

from __future__ import annotations

import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any


@dataclass(frozen=True)
class PRResult:
    """Outcome of :func:`create_pr`."""

    opened: bool  # True iff gh pr create succeeded
    url: str | None  # PR URL on success
    skipped_reason: str | None  # reason if not opened
    stdout: str
    stderr: str


def _gh_available() -> bool:
    return shutil.which("gh") is not None


def _run_gh(cwd: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["gh", *args],
        cwd=str(cwd),
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )


def create_pr(
    worktree: Path,
    *,
    title: str,
    body: str,
    base: str = "main",
    draft: bool = True,
) -> PRResult:
    """Open a PR for the current branch in ``worktree``.

    Parameters
    ----------
    worktree:
        Path to the git worktree where the changes were made.
    title, body:
        PR title and body.
    base:
        Target branch (default ``"main"``).
    draft:
        If True (default), the PR is opened as a draft. Drafts
        cannot be merged accidentally, which is the safer default
        for a development-time tool.

    Returns
    -------
    PRResult
        The outcome. ``opened=False`` with a ``skipped_reason`` if
        the helper could not produce a PR (gh missing, no commits,
        no diff, etc.). The caller can inspect the result and
        decide what to log.
    """
    if not _gh_available():
        return PRResult(
            opened=False,
            url=None,
            skipped_reason="gh not installed",
            stdout="",
            stderr="",
        )

    # Check that the branch has commits ahead of base
    cmp = _run_gh(
        worktree,
        "pr",
        "view",
        base,
        "--json",
        "number",
        "-q",
        ".number",
    )
    if cmp.returncode != 0 and "no pull requests" not in (cmp.stderr or "").lower():
        # gh pr view can fail for many reasons; we proceed anyway.
        pass

    args = [
        "pr",
        "create",
        "--title",
        title,
        "--body",
        body,
        "--base",
        base,
    ]
    if draft:
        args.append("--draft")

    proc = _run_gh(worktree, *args)
    if proc.returncode != 0:
        return PRResult(
            opened=False,
            url=None,
            skipped_reason=f"gh pr create failed: {proc.stderr.strip()[:200]}",
            stdout=proc.stdout,
            stderr=proc.stderr,
        )

    # gh pr create prints the URL on stdout
    url = proc.stdout.strip().splitlines()[-1] if proc.stdout.strip() else None
    return PRResult(
        opened=True,
        url=url,
        skipped_reason=None,
        stdout=proc.stdout,
        stderr=proc.stderr,
    )


def build_pr_body(result: Any) -> str:
    """Build a PR body string from a :class:`LoopResult`."""
    lines = [
        "## AACM loop result",
        "",
        f"- Iterations run: {result.iterations_run}",
        f"- Stop reason: {result.stop_reason.value if result.stop_reason else 'n/a'}",
        f"- Started: {result.started_at}",
        f"- Finished: {result.finished_at}",
        "",
        "### Iterations",
        "",
    ]
    for i, it in enumerate(result.iterations, 1):
        lines.append(
            f"- {i}. strategy={it.strategy} "
            f"admitted={it.proposal_admitted} "
            f"fallback={'reg' if it.fallback_registered else ('discard' if it.fallback_discarded else 'no')}"
        )
    lines.extend(
        [
            "",
            "---",
            "",
            "Generated by `python -m q_speace.aacm.loop`. "
            "Auto-generated; review carefully before merging.",
        ]
    )
    return "\n".join(lines)
